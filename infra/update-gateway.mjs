import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {CloudFormationClient,DescribeStacksCommand,UpdateStackCommand,waitUntilStackUpdateComplete} from '@aws-sdk/client-cloudformation';
import {S3Client,PutObjectCommand} from '@aws-sdk/client-s3';
if(!process.env.AWS_PROFILE||!process.env.AWS_REGION)throw new Error('Set AWS_PROFILE and AWS_REGION.');
const cf=new CloudFormationClient({}),s3=new S3Client({}),StackName='agent-office-mvp';
const current=(await cf.send(new DescribeStacksCommand({StackName}))).Stacks[0];
if(!['CREATE_COMPLETE','UPDATE_COMPLETE'].includes(current.StackStatus))throw new Error(`Wait for the current deployment: ${current.StackStatus}`);
const build=spawnSync(process.execPath,['scripts/package-gateway.mjs'],{stdio:'inherit'});
if(build.error||build.status!==0)throw new Error('Gateway packaging failed.');
const zip=await readFile('infra/generated/gateway.zip');
const key=`gateway/${createHash('sha256').update(zip).digest('hex').slice(0,16)}.zip`;
const bucket=current.Parameters.find(p=>p.ParameterKey==='GatewayBucket').ParameterValue;
await s3.send(new PutObjectCommand({Bucket:bucket,Key:key,Body:zip}));
await cf.send(new UpdateStackCommand({StackName,UsePreviousTemplate:true,Capabilities:['CAPABILITY_IAM'],Parameters:current.Parameters.map(p=>p.ParameterKey==='GatewayKey'?{ParameterKey:p.ParameterKey,ParameterValue:key}:{ParameterKey:p.ParameterKey,UsePreviousValue:true})}));
console.log('Updating gateway through CloudFormation.');
await waitUntilStackUpdateComplete({client:cf,maxWaitTime:600,minDelay:5,maxDelay:15},{StackName});
console.log('Gateway update complete.');
